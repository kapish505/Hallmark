/**
 * Cross-language parity vectors (section 10/13): TypeScript computes normalization validity,
 * overlap, bond/window math and commitments; Foundry asserts Solidity gets the same answers.
 *   pnpm gen:vectors   -> contracts/test/generated/Vectors.sol
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { auditFee, deterrenceBond, fairnessCeiling, NO_CEILING, normalize, overlapText, validate, type NormSpec } from "../packages/shared/src/index.js";

let seed = 7;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
const WORDS = ["the", "a", "fox", "dog", "it's", "total", "42", "o'clock", "exit", "lane", "x", "brown"];
const hex = (s: string) => "hex\"" + Buffer.from(s, "utf8").toString("hex") + "\"";

const raw: string[] = ["", "a", "Hello, World!", "it's 2 o'clock", "TOTAL: $42.50", "a/b_c-d", "  x  ", "it’s"];
for (let i = 0; i < 40; i++) {
  const n = 1 + Math.floor(rnd() * 12);
  raw.push(Array.from({ length: n }, () => WORDS[Math.floor(rnd() * WORDS.length)]).join(rnd() < 0.2 ? "  " : " ") + (rnd() < 0.2 ? " " : ""));
}

const norm: string[] = [];
for (const r of raw) {
  for (const spec of [1, 2] as NormSpec[]) {
    let ok = true;
    let words = 0;
    try {
      words = validate(r, spec);
    } catch {
      ok = false;
    }
    norm.push(`        v.push(NormCase(${hex(r)}, ${spec}, ${ok}, ${words}));`);
  }
}

const ov: string[] = [];
const texts = raw.map((r) => normalize(r.replace(/’/g, "'"), 1).text);
for (let i = 0; i < 60; i++) {
  const a = texts[Math.floor(rnd() * texts.length)];
  const b = texts[Math.floor(rnd() * texts.length)];
  ov.push(`        v.push(OverlapCase(${hex(a)}, ${hex(b)}, ${overlapText(a, b)}));`);
}

const bonds: string[] = [];
for (let i = 0; i < 60; i++) {
  const c = BigInt(Math.floor(rnd() * 1e9));
  const fee = BigInt(1 + Math.floor(rnd() * 1e8));
  const audit = 1 + Math.floor(rnd() * 10000);
  const pi = 1 + Math.floor(rnd() * 10000);
  const fp = rnd() < 0.3 ? 0 : Math.floor(rnd() * 10000);
  const margin = BigInt(Math.floor(rnd() * 1e8));
  const minBond = BigInt(Math.floor(rnd() * 1e7));
  const arb = BigInt(Math.floor(rnd() * 1e8));
  const ceil = fairnessCeiling(margin, audit, fp);
  bonds.push(
    `        v.push(BondCase(${c}, ${fee}, ${audit}, ${pi}, ${fp}, ${margin}, ${minBond}, ${arb}, ${deterrenceBond(c, fee, audit, pi, minBond)}, ${ceil === NO_CEILING ? "type(uint256).max" : ceil}, ${auditFee(audit, arb)}));`,
  );
}

function lib(name: string, type: string, lines: string[]) {
  const body = lines.map((l, i) => l.replace(/^\s*v\.push\(/, `        o[${i}] = `).replace(/\)\);$/, ");")).join("\n");
  return `    function ${name}() internal pure returns (${type}[] memory o) {\n        o = new ${type}[](${lines.length});\n${body}\n    }`;
}
const out = `// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen-vectors.ts. Do not edit.
pragma solidity 0.8.24;

struct NormCase { bytes text; uint8 spec; bool ok; uint256 words; }
struct OverlapCase { bytes a; bytes b; uint256 bps; }
struct BondCase { uint256 c; uint256 fee; uint256 auditBps; uint256 piBps; uint256 fpBps; uint256 margin; uint256 minBond; uint256 arb; uint256 bond; uint256 ceiling; uint256 auditFee; }

library Vectors {
${lib("normCases", "NormCase", norm)}

${lib("overlapCases", "OverlapCase", ov)}

${lib("bondCases", "BondCase", bonds)}
}
`;
const dir = join(import.meta.dirname, "../contracts/test/generated");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "Vectors.sol"), out);
console.log(`wrote ${norm.length} norm, ${ov.length} overlap, ${bonds.length} bond vectors`);
